-- DMS-specific audit projection and immutable document history.
-- Existing audit_logs remains the shared enterprise audit framework.

CREATE TABLE dms_document_audit (
    id              UUID PRIMARY KEY,
    document_id     UUID,
    entity_type     VARCHAR(100) NOT NULL,
    entity_id       UUID,
    action          VARCHAR(100) NOT NULL,
    old_value       TEXT,
    new_value       TEXT,
    actor_id        UUID,
    actor_name      VARCHAR(200),
    ip_address      VARCHAR(100),
    api_path        TEXT,
    http_method     VARCHAR(20),
    success         BOOLEAN NOT NULL DEFAULT TRUE,
    error_message   TEXT,
    created_at      TIMESTAMP NOT NULL,
    CONSTRAINT fk_dms_audit_document
        FOREIGN KEY (document_id) REFERENCES dms_documents (id),
    CONSTRAINT fk_dms_audit_actor
        FOREIGN KEY (actor_id) REFERENCES identity_users (id)
);

CREATE INDEX idx_dms_document_audit_document
    ON dms_document_audit (document_id, created_at DESC);

CREATE INDEX idx_dms_document_audit_action
    ON dms_document_audit (action, created_at DESC);

CREATE INDEX idx_dms_document_audit_entity
    ON dms_document_audit (entity_type, entity_id, created_at DESC);

CREATE INDEX idx_dms_document_audit_actor
    ON dms_document_audit (actor_id, created_at DESC);

CREATE INDEX idx_dms_document_audit_created_at
    ON dms_document_audit (created_at DESC);

CREATE TABLE dms_document_history (
    id              UUID PRIMARY KEY,
    document_id     UUID NOT NULL,
    event_type      VARCHAR(100) NOT NULL,
    entity_type     VARCHAR(100) NOT NULL,
    entity_id       UUID,
    version_number  INTEGER,
    summary         VARCHAR(500) NOT NULL,
    snapshot_json   JSONB,
    actor_id        UUID,
    actor_name      VARCHAR(200),
    created_at      TIMESTAMP NOT NULL,
    CONSTRAINT fk_dms_history_document
        FOREIGN KEY (document_id) REFERENCES dms_documents (id),
    CONSTRAINT fk_dms_history_actor
        FOREIGN KEY (actor_id) REFERENCES identity_users (id),
    CONSTRAINT ck_dms_history_version
        CHECK (version_number IS NULL OR version_number >= 1)
);

CREATE INDEX idx_dms_document_history_document
    ON dms_document_history (document_id, created_at DESC);

CREATE INDEX idx_dms_document_history_event
    ON dms_document_history (event_type, created_at DESC);

-- Preserve DMS events generated by Phases 3-9.
INSERT INTO dms_document_audit (
    id, document_id, entity_type, entity_id, action,
    old_value, new_value, actor_id, actor_name,
    ip_address, api_path, http_method, success, error_message, created_at
)
SELECT
    a.id,
    CASE
        WHEN a.entity_type IN ('DOCUMENT', 'DOCUMENT_PERMISSION', 'DOCUMENT_SHARE')
             AND EXISTS (SELECT 1 FROM dms_documents d WHERE d.id = a.entity_id)
        THEN a.entity_id
        ELSE NULL
    END,
    COALESCE(a.entity_type, 'UNKNOWN'),
    a.entity_id,
    a.action,
    a.old_value,
    a.new_value,
    a.user_id,
    COALESCE(u.full_name, a.username),
    a.ip_address,
    a.api_path,
    a.http_method,
    COALESCE(a.success, TRUE),
    a.error_message,
    a.created_at
FROM audit_logs a
LEFT JOIN identity_users u ON u.id = a.user_id
WHERE a.module = 'DMS';

INSERT INTO dms_document_history (
    id, document_id, event_type, entity_type, entity_id,
    version_number, summary, snapshot_json,
    actor_id, actor_name, created_at
)
SELECT
    gen_random_uuid(),
    a.entity_id,
    a.action,
    COALESCE(a.entity_type, 'DOCUMENT'),
    a.entity_id,
    CASE
        WHEN a.action IN ('UPLOAD', 'VERSION_UPLOAD')
        THEN NULLIF(substring(a.new_value FROM 'version=([0-9]+)'), '')::INTEGER
        ELSE NULL
    END,
    CASE a.action
        WHEN 'UPLOAD' THEN 'Document uploaded'
        WHEN 'METADATA_UPDATE' THEN 'Document metadata updated'
        WHEN 'VERSION_UPLOAD' THEN 'New document version uploaded'
        WHEN 'PERMISSION_GRANT' THEN 'Document permission granted'
        WHEN 'PERMISSION_REVOKE' THEN 'Document permission revoked'
        WHEN 'SHARE' THEN 'Document shared'
        WHEN 'SHARE_REVOKE' THEN 'Document share revoked'
        ELSE a.action
    END,
    jsonb_build_object('oldValue', a.old_value, 'newValue', a.new_value),
    a.user_id,
    COALESCE(u.full_name, a.username),
    a.created_at
FROM audit_logs a
LEFT JOIN identity_users u ON u.id = a.user_id
WHERE a.module = 'DMS'
  AND a.entity_type IN ('DOCUMENT', 'DOCUMENT_PERMISSION', 'DOCUMENT_SHARE')
  AND a.action IN (
      'UPLOAD', 'METADATA_UPDATE', 'VERSION_UPLOAD',
      'PERMISSION_GRANT', 'PERMISSION_REVOKE',
      'SHARE', 'SHARE_REVOKE'
  )
  AND EXISTS (SELECT 1 FROM dms_documents d WHERE d.id = a.entity_id);

CREATE OR REPLACE FUNCTION fn_dms_document_audit_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'dms_document_audit is immutable: % not allowed', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_dms_document_audit_immutable
BEFORE UPDATE OR DELETE ON dms_document_audit
FOR EACH ROW EXECUTE FUNCTION fn_dms_document_audit_immutable();

CREATE OR REPLACE FUNCTION fn_dms_document_history_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'dms_document_history is immutable: % not allowed', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_dms_document_history_immutable
BEFORE UPDATE OR DELETE ON dms_document_history
FOR EACH ROW EXECUTE FUNCTION fn_dms_document_history_immutable();
